package com.example.user.common.error;

/**
 * Enumeration of infrastructure-level error codes for User Service.
 * 
 * <p>
 * These error codes represent technical or infrastructure
 * failures that occur outside of domain / business logic.
 * </p>
 * 
 * <p>
 * Examples include:
 * <ul>
 *   <li>Database connectivity issues</li>
 *   <li>Constraint violations</li>
 *   <li>Schema loading failures</li>
 *   <li>Internal registry misconfiguration</li>
 *   <li>External systems (e.g. Kafka)</li>
 * </ul>
 * </p>
 * 
 * <p>
 * <i>Important design rules</i>:
 * <ul>
 *   <li>
 *     This enum is NOT intended for business validation errors.
 *   </li>
 *   <li>
 *     These errors typically indicate server-side problems.
 *   </li>
 *   <li>
 *     Clients should NOT rely on these codes for business decisions.
 *   </li>
 *   <li>
 *     These errors typically result in HTTP 5xx responses.
 *   </li>
 * </ul>
 * </p>
 */
public enum UserInfrasErrorCode implements ErrorCode {
    // ----- DATABASE -----
    
    /**
     * Indicates a database constraint violation
     * (e.g. unique key constraint).
     */
    DATABASE_CONSTRAINT_VIOLATION(
        "DATABASE_CONSTRAINT_VIOLATION",
        "Database constraint violation"
    ),


    /**
     * Indicates that the application cannot connect
     * to database or database is unavailable
     */
    DATABASE_UNAVAILABLE(
        "DATABASE_UNAVAILABLE",
        "Cannot connect to database"
    ),
    // ----- -----
    
    // ----- Schema -----
    
    /**
     * Indicates that a required schema resource
     * cannot be found in application resources.
     */
    SCHEMA_NOT_FOUND(
        "SCHEMA_NOT_FOUND",
        "Cannot find schema in resources"
    ),

    /**
     * Indicates that a schema file was found
     * but failed to load or parse.
     */
    SCHEMA_LOAD_FAILED(
        "SCHEMA_LOAD_FAILED",
        "Cannot load schema from resources"
    ),
    // ----- -----
    
    // ----- Registry -----
    
    /**
     * Indicates that the component registry
     * is empty when a lookup is attempted.
     */
    COMPONENT_REGISTRY_EMPTY(
        "COMPONENT_REGISTRY_EMPTY",
        "Component registry is empty"
    ),
    
    /**
     * Indicates that duplicate components 
     * were registered with the same key.
     */
    DUPLICATE_COMPONENT(
        "DUPLICATE_COMPONENT",
        "Duplicate component detected in registry"
    ),

    /**
     * Indicates that a required component
     * could not be found in the registry.
     */
    COMPONENT_NOT_FOUND(
        "COMPONENT_NOT_FOUND",
        "Invalid component key generated by key extractor"
    ),

    /**
     * Indicates that a component key generated by
     * keyExtractor is invalid.
     */
    INVALID_COMPONENT_KEY(
        "INVALID_COMPONENT_KEY",
        "Invalid component key generated by key extractor"
    ),
    // ----- -----
    
    // ----- Kafka -----

    /**
     * Indicates that publishing a message to Kafka failed.
     */
    KAFKA_PRODUCE_FAILED(
        "KAFKA_PRODUCE_FAILED",
        "Failed to publish message to Kafka"
    ),

    // ----- -----
    ;

    private final String code;
    private final String message;

    /**
     * Constructs an infrastructure error code with the given code and message.
     *
     * @param code unique error identifier
     * @param message descriptive error message
     */
    private UserInfrasErrorCode(String code, String message) {
        this.code = code;
        this.message = message;
    }

    /**
     * Returns the unique error code.
     *
     * @return error code as a string
     */

    public String code() {
        return this.code;
    }

    /**
     * Returns the human-readable error message.
     *
     * @return error message
     */
    public String message() {
        return this.message;
    }

}
